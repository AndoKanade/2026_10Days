#pragma once

#include <cstdint>

// =============================================================================
// 難易度
// 通電が成立したときに、どこまでのマスを消すかを決める。
// タイトル画面で選び、SceneManager 経由で GameScene と Board へ渡す。
// =============================================================================
enum class Difficulty{

	// 通電したかたまりが通っている横列を丸ごと消す。
	// 配線が噛み合わなかったマスも一緒に片付くため、盤面が詰みにくい。
	Easy,

	// 通電したかたまりのマスをすべて消す。枝分かれもループも含む。
	// 置いたブロックは通電すれば丸ごと消えるが、繋がらなかったマスは残る。
	Normal,

	// 電源とゴールを実際に結んでいるマスだけを消す。
	// 経路から外れた行き止まりの枝は盤面に残るため、置き方を誤ると詰みやすい。
	Hard,

	// 種類の総数（末尾に置くこと）
	Count,
};
