#pragma once

#include <cstdint>

// =============================================================================
// 盤面のマス座標を表す構造体
// 3人分担の境界インターフェースで受け渡しに使う共通の型。
// x は左端を0とした列、y は上端を0とした行。
// =============================================================================
struct GridPos{

	// 列（左端が0、右に向かって増加）
	int32_t x = 0;

	// 行（上端が0、下に向かって増加）
	int32_t y = 0;
};
