#pragma once

#include <cstdint>
#include <vector>

#include "GridPos.h"

// =============================================================================
// ブロックの形（配線の形）の定義
// 形ごとに4回転分のマス相対座標テーブルを固定データで持つ。
// ランダムな割り当てはしない。形と配線は常に一致する。
//
// 担当B（BlockShape・FallingBlock）が中身を実装する。
// ここは3人分担の境界インターフェースとして、型と関数の宣言のみ確定させた状態。
// =============================================================================
namespace BlockShape{

	// 変更：ブロックの種類。L字・T字に I字（4マスの棒）と
	// J字（L字の左右反転）を追加した4種類。
	enum class Type{
		L,
		T,
		I,
		J,
	};

	// 追加：ブロックの種類の総数（Type の要素数）。種類の抽選などに使う。
	// Type に種類を足したら、この値も必ず合わせて増やすこと。
	constexpr int32_t kTypeCount = 4;

	// 回転の総数（0〜3の4方向）
	constexpr int32_t kRotationCount = 4;

	// 指定した種類・回転のブロックが占めるマスの相対座標を返す。
	// 相対座標の基準（原点）の取り方は担当Bが決める。
	// rotation は 0〜kRotationCount-1 を想定する。
	//
	// 現状はスタブ。担当Bが形テーブルを実装するまで空の配列を返す。
	const std::vector<GridPos>& GetCells(Type type,int32_t rotation);

	// 追加：指定した種類・回転のブロックの各マスの端子ビット（Terminal::の値）を返す。
	// 並び順は GetCells() と対応する（同じ添字が同じマスを指す）。
	// 配線パターンは形ごとに固定（ランダムな割り当てはしない）。同じブロック内で
	// 隣接するマス同士の繋がりから計算し、先端のマスは反対側の辺も露出させることで
	// 別のブロックの先端と向きが合えば繋がるようにする。
	const std::vector<uint8_t>& GetTerminals(Type type,int32_t rotation);

	// 追加：指定した種類・回転のブロックの各マスの「壁（ゴール）・床（電源）に
	// 実際に届いてよい」端子ビットを返す。並び順は GetCells() と対応する。
	// GetTerminals() と違い、ブロック同士の接続用に露出させた先端のうち、
	// 形ごとに定めた「本来の先端」だけを残した値になる（T字は出っ張りのみ、
	// L字・I字・J字は1本道なので両端とも）。それ以外のマスは0を返す。
	const std::vector<uint8_t>& GetWallTerminals(Type type,int32_t rotation);
}
